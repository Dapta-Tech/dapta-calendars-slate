/**
 * The dC mark: the product's sibling of the dF mark, on the same metrics.
 *
 * A custom logotype, not a typeface: a heavy italic geometric lowercase d cut by
 * a brushstroke, followed by the green C. The d is byte for byte the one the
 * favicon (`app/icon.svg`) and the sibling product share; the viewBox is the
 * same as the dF mark's, so the two products' marks sit at identical letter
 * sizes in identical boxes.
 *
 * Ink is `currentColor`, so the mark inherits whatever text colour it sits in and
 * follows dark/light with no second asset. Only the green is literal.
 *
 * The d's brushstroke is a mask, and a mask needs an id. It comes from `useId`
 * rather than a constant because two instances of the mark are routinely in the
 * DOM at once (the mobile top bar and the desktop rail), and a `url(#id)`
 * resolves to the FIRST element with that id: when that one sits in a
 * `display: none` subtree the mask does not render and the d disappears.
 */

